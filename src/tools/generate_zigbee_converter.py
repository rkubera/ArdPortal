"""Remove indentation and whole-line comments from the common converter tail."""
import argparse
import json
import re
from pathlib import Path
from cpp_format import format_cpp


def compact_js(source):
    """Compact this semicolon-terminated fragment while preserving quoted bytes and token boundaries."""
    # Comments are whole lines; executable source contains no regular-expression or template literals.
    source = '\n'.join(line for line in source.splitlines()
                       if not line.lstrip().startswith('//'))
    tokens = re.findall(r"'(?:\\.|[^'\\])*'|\"(?:\\.|[^\"\\])*\"|\s+|[^\s]", source)
    output = []
    for index, token in enumerate(tokens):
        if not token.isspace():
            output.append(token)
            continue
        previous = output[-1][-1:] if output else ''
        following = tokens[index + 1][:1] if index + 1 < len(tokens) else ''
        word = lambda char: bool(char) and (char.isalnum() or char in '_$')
        if (word(previous) and word(following)) or previous in '+-' or following in '+-':
            output.append(' ')
    return ''.join(output) + '\n'


def generate(root):
    """Return the flash asset; root is the src directory, all control types are retained."""
    source = (root / 'tools/zigbee_converter_tail.js').read_text(encoding='utf-8')
    messages = json.loads((root / 'languages/en.json').read_text(encoding='utf-8'))['strings']
    source = re.sub(r"'@@(export_[a-z0-9_]+)@@'", lambda match: json.dumps(messages[match[1]], ensure_ascii=False), source)
    compact = compact_js(source)
    return ('// Generated by tools/generate_zigbee_converter.py; do not edit.\n'
            '// Author: Radoslaw Kubera (rkubera on GitHub).\n'
            '// SPDX-License-Identifier: MIT\n#pragma once\n'
            'static const char ARD_ZIGBEE_CONVERTER_TAIL[] PROGMEM=R"JS('
            + compact + ')JS";\n')


def main():
    """Generate the shared asset or check freshness; return zero on success."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    destination = root / 'ZigbeeConverterAssets.h'
    output = format_cpp(generate(root), "ZigbeeConverterAssets.h")
    if args.check:
        if not destination.exists() or destination.read_text(encoding='utf-8') != output:
            raise SystemExit('Zigbee converter asset is stale')
    else:
        destination.write_text(output, encoding='utf-8')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
