#!/usr/bin/env python3
"""Generate indexed, delta-encoded Unicode Letter/Number ranges for device names."""
import argparse
import json
from pathlib import Path
from cpp_format import format_cpp

BLOCK_SIZE = 16


def generate():
    # Keep the accepted character set stable across Python/Unicode versions.
    # The source catalogue preserves the original firmware's Unicode 13 ranges.
    catalog = json.loads(Path(__file__).with_name('device_name_characters.json').read_text())
    ranges = catalog['ranges']
    previous = 126
    for first, last in ranges:
        assert 128 <= first <= last <= 0x10ffff and first > previous + 1
        previous = last
    data, blocks = [], []

    def append(value):
        while value >= 128:
            data.append((value & 127) | 128)
            value >>= 7
        data.append(value)

    for i, (first, last) in enumerate(ranges):
        if i % BLOCK_SIZE == 0:
            blocks.append([first & 255, (first >> 8) & 255, first >> 16,
                           len(data) & 255, len(data) >> 8])
        else:
            append(first - ranges[i-1][1] - 1)
        append(last - first)
    assert len(data) <= 65535, 'Unicode range offsets must fit uint16_t'
    lines = ['// Generated by tools/generate_device_name_characters.py.', '#pragma once',
             '#include <Arduino.h>', '#include <stdint.h>', 'namespace ArdDeviceName {',
             f'static constexpr size_t CharacterBlockSize = {BLOCK_SIZE};',
             'static const uint8_t CharacterBlocks[][5] PROGMEM = {']
    lines += ['{'+','.join(hex(b) for b in block)+'},' for block in blocks]
    lines += ['};', '// clang-format off', 'static const uint8_t Characters[] PROGMEM = {']
    lines += [','.join(hex(b) for b in data[i:i+12])+',' for i in range(0,len(data),12)]
    lines += ['};', '// clang-format on', '}']
    return format_cpp('\n'.join(lines)+'\n', 'DeviceNameCharacters.h')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = Path(__file__).resolve().parents[1] / 'DeviceNameCharacters.h'
    text = generate()
    if args.check:
        if target.read_text() != text:
            raise SystemExit('DeviceNameCharacters.h is stale; run tools/generate_device_name_characters.py')
    else:
        target.write_text(text)
