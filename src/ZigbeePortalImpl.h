/** @brief Apply a received setting once and coalesce persistent changes. @param key Field identifier. @param value Setting. @return True on acceptance. */
bool ArdPortal::acceptZigbeeState(const String& key, const ArdJSON::JSONVar& value) {
  if (otaActive() || _rebootPending || mqttTrialActive()) return false;
  const auto& field = _dynamic.field(key);
  bool persist = !field.hasOwnProperty("persist") || field["persist"].asBool();
  ArdJSON::JSONVar patch;
  if (persist) {
    patch = ArdJSON::JSONVar::object();
    patch[key] = value;
    if (!patch.isObjectPatchValid()) return false;
  }
  if (!_appControls.applyAppState(key, value, ChangeSource::Zigbee)) return false;
  // The patch owns only this value; merging transfers members without allocation.
  return !persist || _zigbeeAppQueue.applyObjectPatch(std::move(patch), false);
}
/** @brief Freeze endpoint descriptors after page registration, then advance bounded command/report work. @param now Current time. @return No value. */
void ArdPortal::serviceZigbeeControls(uint32_t now) {
  using namespace ArdZigbeeFields;
  if (_zigbeeAppQueue.length() && _configurationReady && !otaActive() && !portalAndAppConfigBusy() && !_httpWaitingStorage) {
    _zigbeeDrainingRestart = _rebootPending;
    if (scheduleAppPatch(_zigbeeAppQueue, ChangeSource::Zigbee)) _zigbeeAppQueue = V::object();
    _zigbeeDrainingRestart = false;
  }
  if (!_configurationReady || otaActive() || _rebootPending) return;
  bool retryWaiting = false;
  if (_zigbeeRetryPending) {
    retryWaiting = int32_t(now - _zigbeeRetryAt) < 0;
    if (!retryWaiting) _zigbeeRetryPending = false;
  }
  if (!_zigbeeBeginTried) {
    // Async registration callbacks can submit the next page. Never freeze a partial job.
    if (_appConfigPageRegistration || _zigbeeSeenFields != _dynamic.count()) {
#if ARDPORTAL_ZIGBEE_LAYOUT_SUPPORT
      _converterIdentityStarted = false;
      _converterIdentityControl = nullptr;
      _converterHashA = 2166136261UL;
      _converterHashB = 0x9e3779b9UL;
      _converterLayoutReady = false;
#endif
      _zigbeeSeenFields = _dynamic.count();
      _zigbeeRegistrationSince = now;
      return;
    }
    if (uint32_t(now - _zigbeeRegistrationSince) < 1000 || _zigbeeMappingFailed || retryWaiting) return;
    if (_zigbeeBuildIndex < _dynamic.count()) {
      size_t i = _zigbeeBuildIndex;
      if (!ArdHeap::permits(_dynamic.fieldWork(i) + 1024, _dynamic.fieldBlock(i))) return;
      V field = _dynamic.at(i);
      if (!field.isValid() || field.isUndefined()) {
        _zigbeeRetryPending = true;
        _zigbeeRetryAt = now + 1000;
        return;
      }
      if (composite(field)) {
        V& normalized = field;
        if (!ArdHa::normalize(normalized, true)) {
          _zigbeeRetryPending = true;
          _zigbeeRetryAt = now + 1000;
          return;
        }
        V value = getAppConfigValue(field["id"].asString().c_str());
        if (!value.isValid() || value.isUndefined()) {
          _zigbeeRetryPending = true;
          _zigbeeRetryAt = now + 1000;
          return;
        }
        String label = field["name"].asString();
        if (!label.length()) label = field["id"].asString();
        size_t parts = normalized["controls"].length();
        Spec mapped;
        mapped.field = i;
        String suffix;
        if (_zigbeeBuildPart < parts) {
          mapped = describePart(normalized, _zigbeeBuildPart);
          mapped.field = i;
          const V& c = static_cast<const V&>(normalized)["controls"][_zigbeeBuildPart];
          suffix = c["key"].asString();
          if (!suffix.length()) suffix = c["payload"].asString();
        } else if (_zigbeeBuildPart == parts) {
          String type = field["type"].asString();
          if (type == "humidifier" || type == "water_heater") {
            mapped.part = 0xfffe;
            mapped.kind = type == "humidifier" ? Kind::Humidity : Kind::Temperature;
            suffix = "current";
          }
        } else if (_zigbeeBuildPart == parts + 1) {
          uint16_t states = stateCount(normalized);
          if (states) {
            mapped.part = 0xfffe;
            mapped.kind = Kind::State;
            mapped.states = states;
            suffix = "state";
          }
        } else {
          _zigbeeBuildPart = 0;
          _zigbee.diagnostic(ARD_LANG_NATIVE_ZIGBEE_COMPOSITE + field["id"].asString());
          ++_zigbeeBuildIndex;
          return;
        }
        if (mapped.kind != Kind::None) {
          Values values;
          if (mapped.part == 0xfffe && mapped.kind != Kind::State) {
            Spec scalar = mapped;
            scalar.part = 0xffff;
            values = encode(scalar, normalized, value[field["type"].asString() == "humidifier" ? "current_humidity" : "current_temperature"]);
          } else values = encode(mapped, normalized, value);
          if (!_zigbee.addControl(mapped, values, label + " / " + suffix)) {
            _zigbeeMappingFailed = true;
            _zigbee.diagnostic(ARD_LANG_NATIVE_ZIGBEE_COMPOSITE_REGISTRATION_FAILED + field["id"].asString() + ": " + _zigbee.error());
            return;
          }
        }
        ++_zigbeeBuildPart;
        return;
      }
      Spec spec = describe(field, V());
      if (spec.kind == Kind::None && field["type"].asString() != "text") {
        ++_zigbeeBuildIndex;
        return;
      }
      V value = getAppConfigValue(field["id"].asString().c_str());
      if (!value.isValid() || value.isUndefined()) {
        _zigbeeRetryPending = true;
        _zigbeeRetryAt = now + 1000;
        return;
      }
      spec = describe(field, value);
      spec.field = i;
      if (spec.kind != Kind::None) {
        auto values = encode(spec, field, value);
        String label = field["name"].asString();
        if (!label.length()) label = field["id"].asString();
        if (!_zigbee.addControl(spec, values, label)) {
          _zigbeeMappingFailed = true;
          _zigbee.diagnostic(ARD_LANG_NATIVE_ZIGBEE_ENDPOINT_REGISTRATION_FAILED + field["id"].asString() + ": " + _zigbee.error());
          return;
        }
        _zigbee.diagnostic(ARD_LANG_NATIVE_ZIGBEE_ENDPOINT + String(_zigbee.controlCount() + 1) + ": " + field["id"].asString());
      }
      ++_zigbeeBuildIndex;
      return;
    }
#if ARDPORTAL_ZIGBEE_LAYOUT_SUPPORT
    // Hash exactly the exported metadata, one endpoint per loop, before SDK startup.
    if (!_converterIdentityStarted) {
      _converterIdentityControl = _zigbee.controls();
      _converterIdentityStarted = true;
    }
    if (_converterIdentityControl) {
      String part = zigbeeConverterControlJson(*_converterIdentityControl);
      if (!part.length()) return;
      ArdZigbeeConverterLayout::append(_converterHashA, _converterHashB, part.c_str(), part.length());
      _converterIdentityControl = _converterIdentityControl->next.get();
      return;
    }
    char* model = ArdZigbeeIdentity::Model;
    snprintf(model + 1, sizeof(ArdZigbeeIdentity::Model) - 1, "ArdPortal-%08lx%08lx", (unsigned long)_converterHashA, (unsigned long)_converterHashB);
    model[0] = strlen(model + 1);
    _converterLayoutReady = true;
#endif
#if ARDPORTAL_ENABLE_POWER_MANAGEMENT
    prepareZigbeePower();
#endif
    _zigbeeBeginTried = true;
    _zigbee.begin(_zigbeeOptions);
    return;
  }
  if (_zigbeeSeenFields != _dynamic.count()) {
    _zigbeeSeenFields = _dynamic.count();
    _zigbee.diagnostic(ARD_LANG_NATIVE_ZIGBEE_NEW_FIELDS_REQUIRE_RESTART_TO_REBUILD_NATIVE_ENDP);
  }
  bool connected = _zigbee.state() == ZigbeeState::Connected;
  if (connected != _zigbeeWasConnected) {
    if (connected) _zigbee.queueReports(size_t(-1), true);
#if ARDPORTAL_ZIGBEE_OTA_SUPPORT
    if (connected && !_zigbeeWasConnected) _zigbee.queryOta();
#endif
    _zigbeeWasConnected = connected;
  }
  Command& command = _zigbeePendingCommand;
  // One application command per loop; SDK callbacks never call user code.
  if (_zigbeeHasCommand || (_zigbeeHasCommand = _zigbee.nextCommand(command))) {
    for (const auto* entry = _zigbee.controls(); entry; entry = entry->next.get())
      if (entry->spec.endpoint == command.endpoint) {
        if (!ArdHeap::permits(_dynamic.fieldWork(entry->spec.field) + 2048, _dynamic.fieldBlock(entry->spec.field))) return;
        V f = _dynamic.at(entry->spec.field);
        if (!f.isValid() || f.isUndefined() || (ArdHa::extended(f) && !ArdHa::normalize(f, true))) return;
        String id = f["id"].asString();
        V current = getAppConfigValue(id.c_str()), next;
        if (!current.isValid()) return;
        _zigbeeHasCommand = false;
        String action, property;
        bool accepted = false;
        if (f.isValid() && !ArdHa::readonly(f) && decode(entry->spec, f, current, command, next, action, property)) {
          if (ArdHa::extended(f)) {
            const V& normalized = f;
            {
              if (entry->spec.part != 0xffff && entry->spec.part < normalized["controls"].length()) accepted = _appControls.appControl(f, entry->spec.part, action.length() ? V(action) : next, ChangeSource::Zigbee);
              else if ((entry->spec.kind == Kind::Siren || entry->spec.kind == Kind::Light) && !action.length() && !property.length()) accepted = ArdHa::validValue(normalized, next) && acceptZigbeeState(id, next);
              else
                for (size_t i = 0; i < normalized["controls"].length(); ++i) {
                  const V& control = static_cast<const V&>(normalized)["controls"][i];
                  if (action.length() ? control["type"].asString() == "action" && control["payload"].asString() == action : control["key"].asString() == property) {
                    accepted = _appControls.appControl(f, i, action.length() ? V(action) : next, ChangeSource::Zigbee);
                    break;
                  }
                }
            }
          } else if (ArdDynamicPages::validValue(f, next)) accepted = acceptZigbeeState(id, next);
        }
        _zigbee.diagnostic(ARD_LANG_NATIVE_ZIGBEE_RX + id + (accepted ? ARD_LANG_NATIVE_ACCEPTED : ARD_LANG_NATIVE_REJECTED));
        _zigbee.queueReports(entry->spec.field, true);
        break;
      }
  }
  if (!connected || int32_t(now - _zigbeeReportReadyAt) < 0) return;
  const auto* entry = _zigbee.nextReport(now, _zigbeeReportEndpoint);
  if (!entry) return;
  _zigbeeReportReadyAt = now + 50;
  _zigbeeReportEndpoint = entry->spec.endpoint;
  size_t index = entry->spec.field;
  if (!ArdHeap::permits(_dynamic.fieldWork(index) + 1024, _dynamic.fieldBlock(index))) return;
  V f = _dynamic.at(index);
  if (!f.isValid() || f.isUndefined() || (composite(f) && !ArdHa::normalize(f, true))) {
    _zigbee.finishReport(entry->spec.endpoint, false, now);
    return;
  }
  V state = getAppConfigValue(f["id"].asString().c_str());
  Values values;
  if (entry->spec.part == 0xfffe && entry->spec.kind != Kind::State) {
    Spec scalar = entry->spec;
    scalar.part = 0xffff;
    values = encode(scalar, f, state[f["type"].asString() == "humidifier" ? "current_humidity" : "current_temperature"]);
  } else values = encode(entry->spec, f, state);
  _zigbee.finishReport(entry->spec.endpoint, _zigbee.publish(entry->spec.endpoint, values, entry->reportForce), now);
}
